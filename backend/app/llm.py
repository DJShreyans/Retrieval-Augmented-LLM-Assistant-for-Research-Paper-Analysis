import json
import time
from typing import List, Dict, Any, Optional, Generator, Type
import requests
from pydantic import BaseModel
from backend.app.config import settings
from backend.app.db import SessionLocal
from backend.app.models import LLMCall

def log_llm_call(purpose: str, model: str, prompt_tokens: int, completion_tokens: int, latency_ms: int, user_id: Optional[int] = None):
    try:
        db = SessionLocal()
        call = LLMCall(
            user_id=user_id,
            purpose=purpose,
            model=model or settings.LLM_PROVIDER,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms
        )
        db.add(call)
        db.commit()
        db.close()
    except Exception as e:
        print(f"[LLM Log Error] {e}")

class LLMService:
    @property
    def provider(self) -> str:
        return (settings.LLM_PROVIDER or "none").lower()

    @property
    def model(self) -> str:
        m = settings.LLM_MODEL
        if not m or m.lower() in ("default", "none", ""):
            return "gemini-2.5-flash" if self.provider == "gemini" else "gpt-4o-mini"
        return m

    @property
    def api_key(self) -> Optional[str]:
        return settings.LLM_API_KEY

    @property
    def base_url(self) -> Optional[str]:
        return settings.LLM_BASE_URL

    def _call_gemini(self, messages: List[Dict[str, str]], system: Optional[str] = None, json_mode: bool = False) -> str:
        """Robust direct REST caller for Google Gemini with model auto-fallback."""
        model = self.model
        if "1.5" in model:
            model = "gemini-2.5-flash"

        contents = []
        for m in messages:
            role = "user" if m.get("role") in ("user", "system") else "model"
            contents.append({"role": role, "parts": [{"text": m.get("content", "")}]})

        payload: Dict[str, Any] = {"contents": contents}
        if system:
            payload["systemInstruction"] = {"parts": [{"text": system}]}
        if json_mode:
            payload["generationConfig"] = {"responseMimeType": "application/json"}

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={self.api_key}"
        res = requests.post(url, json=payload, timeout=25)

        # Fallback to gemini-2.5-flash if 404
        if res.status_code == 404 and model != "gemini-2.5-flash":
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={self.api_key}"
            res = requests.post(url, json=payload, timeout=25)

        res.raise_for_status()
        data = res.json()
        candidates = data.get("candidates", [])
        if candidates:
            parts = candidates[0].get("content", {}).get("parts", [])
            if parts and "text" in parts[0]:
                return parts[0]["text"]
        return "No response generated by model."

    def _stream_gemini(self, messages: List[Dict[str, str]], system: Optional[str] = None) -> Generator[str, None, None]:
        """Robust direct SSE stream caller for Google Gemini."""
        model = self.model
        if "1.5" in model:
            model = "gemini-2.5-flash"

        contents = []
        for m in messages:
            role = "user" if m.get("role") in ("user", "system") else "model"
            contents.append({"role": role, "parts": [{"text": m.get("content", "")}]})

        payload: Dict[str, Any] = {"contents": contents}
        if system:
            payload["systemInstruction"] = {"parts": [{"text": system}]}

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:streamGenerateContent?alt=sse&key={self.api_key}"
        res = requests.post(url, json=payload, stream=True, timeout=25)

        if res.status_code == 404 and model != "gemini-2.5-flash":
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:streamGenerateContent?alt=sse&key={self.api_key}"
            res = requests.post(url, json=payload, stream=True, timeout=25)

        res.raise_for_status()

        for line in res.iter_lines():
            if not line:
                continue
            line_str = line.decode("utf-8")
            if line_str.startswith("data: "):
                try:
                    chunk_data = json.loads(line_str[6:])
                    candidates = chunk_data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        for p in parts:
                            if "text" in p and p["text"]:
                                yield p["text"]
                except Exception:
                    continue

    def complete(self, messages: List[Dict[str, str]], system: Optional[str] = None, user_id: Optional[int] = None) -> str:
        start_time = time.time()
        provider = self.provider

        if provider == "none":
            return "Extractive mode: No LLM provider is connected. Evidence passages are provided below."

        prompt_text = " ".join(m.get("content", "") for m in messages)
        prompt_tokens = len(prompt_text.split())
        output_text = ""

        try:
            if provider == "gemini":
                output_text = self._call_gemini(messages, system=system)
                completion_tokens = len(output_text.split())
            elif provider in ("openai", "openai_compatible"):
                from openai import OpenAI
                client = OpenAI(api_key=self.api_key or "sk-dummy", base_url=self.base_url)
                full_messages = []
                if system:
                    full_messages.append({"role": "system", "content": system})
                full_messages.extend(messages)
                res = client.chat.completions.create(model=self.model, messages=full_messages)
                output_text = res.choices[0].message.content or ""
                completion_tokens = res.usage.completion_tokens if res.usage else len(output_text.split())
            elif provider == "anthropic":
                import anthropic
                client = anthropic.Anthropic(api_key=self.api_key)
                res = client.messages.create(
                    model=self.model or "claude-3-5-sonnet-20241022",
                    system=system or "",
                    messages=messages,
                    max_tokens=2048
                )
                output_text = res.content[0].text
                completion_tokens = res.usage.output_tokens
            else:
                output_text = f"Unsupported LLM provider: {provider}"
                completion_tokens = 0
        except Exception as e:
            print(f"[LLM Error - Falling back safely] {e}")
            output_text = f"Notice: External LLM generation encountered an issue ({str(e)[:120]}). Falling back to grounded evidence."
            completion_tokens = 0

        latency_ms = int((time.time() - start_time) * 1000)
        log_llm_call("complete", self.model, prompt_tokens, completion_tokens, latency_ms, user_id)
        return output_text

    def stream(self, messages: List[Dict[str, str]], system: Optional[str] = None, user_id: Optional[int] = None) -> Generator[str, None, None]:
        start_time = time.time()
        provider = self.provider

        if provider == "none":
            text = "Top evidence (no LLM connected):\n\n"
            for word in text.split(" "):
                yield word + " "
                time.sleep(0.01)
            return

        try:
            if provider == "gemini":
                total_tokens = 0
                for token in self._stream_gemini(messages, system=system):
                    total_tokens += 1
                    yield token
                latency_ms = int((time.time() - start_time) * 1000)
                log_llm_call("stream", self.model, len(messages), total_tokens, latency_ms, user_id)
                return

            if provider in ("openai", "openai_compatible"):
                from openai import OpenAI
                client = OpenAI(api_key=self.api_key or "sk-dummy", base_url=self.base_url)
                full_messages = []
                if system:
                    full_messages.append({"role": "system", "content": system})
                full_messages.extend(messages)
                response = client.chat.completions.create(model=self.model, messages=full_messages, stream=True)
                total_tokens = 0
                for chunk in response:
                    delta = chunk.choices[0].delta.content if chunk.choices else ""
                    if delta:
                        total_tokens += 1
                        yield delta
                latency_ms = int((time.time() - start_time) * 1000)
                log_llm_call("stream", self.model, len(messages), total_tokens, latency_ms, user_id)
                return

            # Fallback
            full_res = self.complete(messages, system=system, user_id=user_id)
            for word in full_res.split(" "):
                yield word + " "
                time.sleep(0.01)

        except Exception as e:
            print(f"[LLM Stream Error - Safe Fallback] {e}")
            fallback_text = f"Notice: Live streaming encountered a temporary error ({str(e)[:100]}). Falling back to grounded evidence cards:\n\n"
            for word in fallback_text.split(" "):
                yield word + " "
                time.sleep(0.01)

    def structured(
        self,
        messages: List[Dict[str, str]],
        schema: Type[BaseModel],
        system: Optional[str] = None,
        user_id: Optional[int] = None,
        retries: int = 2
    ) -> BaseModel:
        sys_prompt = (system or "") + f"\nOutput ONLY valid JSON adhering strictly to the schema: {schema.model_json_schema()}"
        last_err = None

        for attempt in range(retries + 1):
            try:
                if self.provider == "gemini":
                    raw_json = self._call_gemini(messages, system=sys_prompt, json_mode=True)
                else:
                    raw_json = self.complete(messages, system=sys_prompt, user_id=user_id)

                cleaned = raw_json.strip()
                if cleaned.startswith("```json"):
                    cleaned = cleaned[7:]
                if cleaned.startswith("```"):
                    cleaned = cleaned[3:]
                if cleaned.endswith("```"):
                    cleaned = cleaned[:-3]
                parsed_data = json.loads(cleaned.strip())
                return schema.model_validate(parsed_data)
            except Exception as e:
                last_err = e
                time.sleep(0.5)

        # Fallback to schema empty default instead of hard crashing
        try:
            return schema()
        except Exception:
            raise RuntimeError(f"Failed to generate valid structured response: {last_err}")

llm_service = LLMService()

def get_llm_client() -> LLMService:
    return llm_service
